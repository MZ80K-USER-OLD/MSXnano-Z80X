; Signed index displacement and LEA.L test. Memory writes use banks 01/02 only.
    ORG 0100H
START:
    DI
    DEFB 0EDH,090H
    LD (SAVED_SP),SP
    DEFB 0EDH,00CH
    LD (SAVED_BANKS),A
    DEFB 0EDH,01CH
    LD (SAVED_BANKS+1),A
    DEFB 0EDH,02CH
    LD (SAVED_BANKS+2),A
    DEFB 0EDH,00DH
    LD (SAVED_BANKS+3),A
    DEFB 0EDH,01DH
    LD (SAVED_BANKS+4),A
    DEFB 0EDH,092H
    DEFB 0EDH,036H
    LD (SAVED_MSP),HL
    DEFB 0EDH,02CH
    LD (SAVED_MSP+2),A
    DEFB 0EDH,090H
    XOR A
    LD (PASS_COUNT),A
    LD (FAIL_COUNT),A
    LD (CASE_ID),A
    LD (MODE_NUMBER),A
    LD (VARIANT),A
    LD (ROW_NUMBER),A
NEXT_LEA:
    CALL PREPARE
    LD A,(VARIANT)
    AND 1
    ADD A,068H
    LD (LEA_OPCODE),A
    LD A,(DISPLACEMENT)
    LD (LEA_DISP),A
    CALL ENTER_MODE
    LD BC,000D7H
    PUSH BC
    POP AF
LEA_INSTRUCTION:
    DEFB 0DDH,0EDH
LEA_OPCODE: DEFB 068H
LEA_DISP: DEFB 0
    PUSH AF
    POP BC
    LD A,C
    LD (ACTUAL+3),A
    LD A,(VARIANT)
    AND 1
    JR Z,CAPTURE_HL
    LD (ACTUAL),DE
    DEFB 0EDH,01CH
    JR CAPTURE_BANK
CAPTURE_HL:
    LD (ACTUAL),HL
    DEFB 0EDH,02CH
CAPTURE_BANK:
    LD (ACTUAL+2),A
    LD (ACTUAL+4),IX
    LD (ACTUAL+6),IY
    DEFB 0EDH,00DH
    LD (ACTUAL+8),A
    DEFB 0EDH,01DH
    LD (ACTUAL+9),A
    DEFB 0EDH,090H
    CALL RESET_BANKS
    LD HL,ACTUAL
    LD DE,EXPECTED
    LD B,10
    CALL CHECK_CASE
    LD A,(ROW_NUMBER)
    INC A
    AND 7
    LD (ROW_NUMBER),A
    JP NZ,NEXT_LEA
    LD A,(VARIANT)
    INC A
    AND 3
    LD (VARIANT),A
    JP NZ,NEXT_LEA
    LD A,(MODE_NUMBER)
    INC A
    LD (MODE_NUMBER),A
    CP 3
    JP C,NEXT_LEA
    LD A,1
    LD (MODE_NUMBER),A
NEXT_MEMORY:
    ; Rows 0/1 exercise actual +32 carry and -32 borrow at safe RAM addresses.
    CALL PREPARE
    CALL ENTER_MODE
    LD A,(EXPECTED+2)
    DEFB 0EDH,024H
    LD HL,(EXPECTED)
    LD (HL),0
    LD BC,000D7H
    PUSH BC
    POP AF
    LD A,0A5H
STORE_INSTRUCTION:
    DEFB 0DDH,077H
STORE_DISP: DEFB 0
    PUSH AF
    POP BC
    LD A,C
    LD (ACTUAL+1),A
    LD A,(HL)
    LD (ACTUAL),A
    LD (HL),05AH
READ_INSTRUCTION:
    DEFB 0DDH,07EH
READ_DISP: DEFB 0
    LD (ACTUAL+2),A
    DEFB 0EDH,090H
    CALL RESET_BANKS
    LD HL,ACTUAL
    LD DE,MEMORY_EXPECTED
    LD B,3
    CALL CHECK_CASE
    LD A,(ROW_NUMBER)
    XOR 1
    LD (ROW_NUMBER),A
    JP NZ,NEXT_MEMORY
    LD A,(VARIANT)
    XOR 2
    LD (VARIANT),A
    JP NZ,NEXT_MEMORY
    LD A,(MODE_NUMBER)
    INC A
    LD (MODE_NUMBER),A
    CP 3
    JP C,NEXT_MEMORY
    LD (CURRENT_SP),SP
    LD HL,CURRENT_SP
    LD DE,SAVED_SP
    LD B,2
    CALL CHECK_CASE
    DEFB 0EDH,092H
    LD A,(SAVED_MSP+2)
    DEFB 0EDH,024H
    LD HL,(SAVED_MSP)
    DEFB 0EDH,035H
    DEFB 0EDH,090H
    LD A,(SAVED_BANKS)
    DEFB 0EDH,004H
    LD A,(SAVED_BANKS+1)
    DEFB 0EDH,014H
    LD A,(SAVED_BANKS+2)
    DEFB 0EDH,024H
    LD A,(SAVED_BANKS+3)
    DEFB 0EDH,005H
    LD A,(SAVED_BANKS+4)
    DEFB 0EDH,015H
    EI
    LD DE,BANNER
    CALL PRINT
    LD A,(PASS_COUNT)
    CALL HEX
    LD DE,FAIL_TEXT
    CALL PRINT
    LD A,(FAIL_COUNT)
    CALL HEX
    LD A,(FAIL_COUNT)
    OR A
    JR Z,DONE
    LD DE,FIRST_TEXT
    CALL PRINT
    LD A,(FIRST_CASE)
    CALL HEX
    LD DE,OFFSET_TEXT
    CALL PRINT
    LD A,(FIRST_OFFSET)
    CALL HEX
DONE:
    LD DE,CRLF
    CALL PRINT
    LD C,0
    CALL 5
    RET

PREPARE:
    CALL RESET_BANKS
    LD A,(ROW_NUMBER)
    LD L,A
    LD H,0
    ADD HL,HL
    ADD HL,HL
    ADD HL,HL
    LD DE,ROWS
    ADD HL,DE
    LD E,(HL)
    INC HL
    LD D,(HL)
    INC HL
    LD A,(HL)
    LD (BASE_BANK),A
    INC HL
    LD A,(HL)
    LD (DISPLACEMENT),A
    LD (STORE_DISP),A
    LD (READ_DISP),A
    INC HL
    PUSH DE
    LD DE,EXPECTED
    LD BC,3
    LDIR
    POP DE
    LD A,(MODE_NUMBER)
    OR A
    JR NZ,EXPECTED_BANK_READY
    XOR A
    LD (EXPECTED+2),A
EXPECTED_BANK_READY:
    LD A,0D7H
    LD (EXPECTED+3),A
    LD (EXPECTED+4),DE
    LD (EXPECTED+6),DE
    PUSH DE
    POP IX
    PUSH DE
    POP IY
    LD A,(VARIANT)
    AND 2
    LD A,0DDH
    JR Z,PREFIX_READY
    LD A,0FDH
PREFIX_READY:
    LD (LEA_INSTRUCTION),A
    LD (STORE_INSTRUCTION),A
    LD (READ_INSTRUCTION),A
    CP 0DDH
    JR NZ,IY_SELECTED
    LD IY,06789H
    LD HL,06789H
    LD (EXPECTED+6),HL
    LD A,(BASE_BANK)
    LD B,067H
    JR BANKS_READY
IY_SELECTED:
    LD IX,04567H
    LD HL,04567H
    LD (EXPECTED+4),HL
    LD A,(BASE_BANK)
    LD B,A
    LD A,045H
BANKS_READY:
    DEFB 0EDH,005H
    LD (EXPECTED+8),A
    LD A,B
    DEFB 0EDH,015H
    LD (EXPECTED+9),A
    LD HL,01234H
    LD DE,05678H
    RET
ENTER_MODE:
    LD A,(MODE_NUMBER)
    OR A
    RET Z
    CP 1
    JR Z,ENTER_M1
    LD (RETURN_WORD),HL
    LD HL,0F000H
    LD A,2
    DEFB 0EDH,024H
    DEFB 0EDH,035H
    XOR A
    DEFB 0EDH,024H
    LD HL,(RETURN_WORD)
    ; Return in M0; changing stack mode inside a called routine is unsafe.
    POP BC
    DEFB 0EDH,092H
    PUSH BC
    RET
ENTER_M1:
    DEFB 0EDH,091H
    RET
RESET_BANKS:
    XOR A
    DEFB 0EDH,004H,0EDH,014H,0EDH,024H,0EDH,005H,0EDH,015H
    RET
CHECK_CASE:
    LD C,0
COMPARE:
    LD A,(DE)
    CP (HL)
    JR NZ,FAILED
    INC HL
    INC DE
    INC C
    DJNZ COMPARE
    LD HL,PASS_COUNT
    INC (HL)
    JR CHECK_DONE
FAILED:
    LD A,(FAIL_COUNT)
    OR A
    JR NZ,FAIL_RECORDED
    LD A,(CASE_ID)
    LD (FIRST_CASE),A
    LD A,C
    LD (FIRST_OFFSET),A
FAIL_RECORDED:
    LD HL,FAIL_COUNT
    INC (HL)
CHECK_DONE:
    LD HL,CASE_ID
    INC (HL)
    RET
PRINT:
    LD C,9
    CALL 5
    RET
HEX:
    PUSH AF
    RRCA
    RRCA
    RRCA
    RRCA
    CALL NIBBLE
    POP AF
NIBBLE:
    AND 00FH
    ADD A,'0'
    CP '9'+1
    JR C,EMIT
    ADD A,7
EMIT:
    LD E,A
    LD C,2
    CALL 5
    RET

; Each row: base word, base bank, signed displacement, expected word/bank, pad.
ROWS:
    DEFW 0FFF0H
    DEFB 1,020H
    DEFW 0010H
    DEFB 2,0
    DEFW 0010H
    DEFB 2,0E0H
    DEFW 0FFF0H
    DEFB 1,0
    DEFW 0FFC0H
    DEFB 1,07FH
    DEFW 003FH
    DEFB 2,0
    DEFW 0040H
    DEFB 2,080H
    DEFW 0FFC0H
    DEFB 1,0
    DEFW 0FFFFH
    DEFB 0FFH,1
    DEFW 0
    DEFB 0,0
    DEFW 0
    DEFB 0,0FFH
    DEFW 0FFFFH
    DEFB 0FFH,0
    DEFW 03456H
    DEFB 012H,0
    DEFW 03456H
    DEFB 012H,0
    DEFW 08000H
    DEFB 07FH,080H
    DEFW 07F80H
    DEFB 07FH,0
MEMORY_EXPECTED: DEFB 0A5H,0D7H,05AH
BANNER: DEFB "INDEXEA: signed IX/IY + LEA.L",13,10,"PASS=$"
FAIL_TEXT: DEFB " FAIL=$"
FIRST_TEXT: DEFB " FIRST CASE=$"
OFFSET_TEXT: DEFB " OFFSET=$"
CRLF: DEFB 13,10,"$"
PASS_COUNT: DEFB 0
FAIL_COUNT: DEFB 0
CASE_ID: DEFB 0
FIRST_CASE: DEFB 0
FIRST_OFFSET: DEFB 0
MODE_NUMBER: DEFB 0
VARIANT: DEFB 0
ROW_NUMBER: DEFB 0
BASE_BANK: DEFB 0
DISPLACEMENT: DEFB 0
EXPECTED: DEFS 10
ACTUAL: DEFS 10
RETURN_WORD: DEFW 0
SAVED_SP: DEFW 0
CURRENT_SP: DEFW 0
SAVED_BANKS: DEFS 5
SAVED_MSP: DEFS 3
