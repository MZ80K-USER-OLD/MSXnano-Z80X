; V16.1 DI-only RST.L/IBR/SYSCALL hardware test, physical banks 00/01/02.
    ORG 0100H
START:
    DI
    DEFB 0EDH,090H
    CALL RESET_BANKS
    LD A,I
    LD (SAVED_I),A
    DEFB 0EDH,0EFH
    LD (SAVED_IBR),A
    DEFB 0EDH,036H
    LD (SAVED_MSP),HL
    DEFB 0EDH,02CH
    LD (SAVED_MSP+2),A
    CALL RESET_BANKS
    EI
    LD DE,BANNER
    CALL PRINT
NEXT_CASE:
    DI
    LD (EXPECTED+10),SP
    XOR A
    LD (ACTUAL),A
    LD (EXPECTED+7),A
    LD (EXPECTED+8),A
    LD (EXPECTED+9),A
    LD (EXPECTED+4),A
    LD A,0E0H
    LD (EXPECTED+5),A
    LD A,2
    LD (EXPECTED+6),A
    LD A,05AH
    LD (EXPECTED),A
    LD A,(CASE_ID)
    CP 24
    JP NC,PREP_NOP
    AND 1
    JR Z,STACK_READY
    XOR A
    LD (EXPECTED+5),A
STACK_READY:
    LD A,(CASE_ID)
    SRL A
    CP 8
    JR NC,PREP_SYSCALL
    LD C,A
    ADD A,A
    ADD A,A
    ADD A,A
    ADD A,085H
    LD (CODE+1),A
    XOR A
    LD (CODE+2),A
    LD A,C
    ADD A,A
    ADD A,A
    ADD A,A
    LD L,A
    LD H,0
    LD DE,VECTOR
    LD C,5
    LD A,2
    DEFB 0EDH,024H
    DEFB 0EDH,091H
    CALL COPY_BYTES
    JR PREP_MAIN
PREP_SYSCALL:
    SUB 8
    LD E,A
    LD D,0
    LD HL,OPERANDS
    ADD HL,DE
    LD A,(HL)
    LD (CODE+2),A
    LD L,A
    LD H,040H
    CP 0FFH
    JR NZ,TABLE_READY
    LD H,0FFH
TABLE_READY:
    LD A,H
    LD I,A
    LD A,0C6H
    LD (CODE+1),A
    DEFB 0EDH,091H
    LD A,2
    DEFB 0EDH,024H
    LD (HL),0
    INC HL
    LD (HL),081H
PREP_MAIN:
    LD A,(CODE+1)
    CP 0C6H
    LD A,2
    JR NZ,RETURN_READY
    INC A
RETURN_READY:
    LD (EXPECTED+7),A
    LD A,080H
    LD (EXPECTED+8),A
    LD A,1
    LD (EXPECTED+9),A
    LD HL,08000H
    DEFB 0EDH,024H
    LD DE,CODE
    LD C,CODE_END-CODE
    CALL COPY_BYTES
    LD A,2
    DEFB 0EDH,024H
    LD HL,08100H
    LD DE,HANDLER
    LD C,4
    CALL COPY_BYTES
    JP PREP_STACK
PREP_NOP:
    SUB 24
    ADD A,090H
    LD (NOP_MODE+1),A
    LD A,0A6H
    LD (EXPECTED),A
    DEFB 0EDH,091H
PREP_STACK:
    LD A,2
    DEFB 0EDH,03AH
    LD A,(EXPECTED+6)
    DEFB 0EDH,024H
    LD HL,(EXPECTED+4)
    DEFB 0EDH,035H
    ; Initialize the three frame bytes without changing MSP.
    LD A,(EXPECTED+5)
    OR A
    LD HL,0DFFDH
    LD A,2
    JR NZ,FRAME_READY
    LD HL,0FFFDH
    DEC A
FRAME_READY:
    DEFB 0EDH,024H
    LD (HL),0
    INC HL
    LD (HL),0
    INC HL
    LD (HL),0
    DEFB 0EDH,090H
    CALL RESET_BANKS
    LD A,(CASE_ID)
    CP 24
    JR NC,RUN_NOP
    LD BC,00D7H
    PUSH BC
    POP AF
    DEFB 0EDH,09BH,000H,080H,001H
RUN_NOP:
    LD BC,00D7H
    PUSH BC
    POP AF
NOP_MODE:
    DEFB 0EDH,090H
    DEFB 0EDH,085H,0EDH,08DH,0EDH,095H,0EDH,09DH
    DEFB 0EDH,0A5H,0EDH,0ADH,0EDH,0B5H,0EDH,0BDH
    DEFB 0EDH,0C6H,03EH,0A6H
    LD (ACTUAL),A
    DEFB 0EDH,090H
RETURN_M0:
    PUSH AF
    POP BC
    LD A,C
    LD (ACTUAL+1),A
    LD A,I
    PUSH AF
    POP BC
    LD A,C
    AND 4
    LD (ACTUAL+2),A
    DEFB 0EDH,0EFH
    LD (ACTUAL+3),A
    DEFB 0EDH,036H
    LD (ACTUAL+4),HL
    DEFB 0EDH,02CH
    LD (ACTUAL+6),A
    LD (ACTUAL+10),SP
    DEFB 0EDH,091H
    LD A,(EXPECTED+5)
    OR A
    LD HL,0DFFDH
    LD A,2
    JR NZ,READ_FRAME
    LD HL,0FFFDH
    DEC A
READ_FRAME:
    DEFB 0EDH,024H
    LD DE,ACTUAL+7
    LD B,3
READ_BYTE:
    LD A,(HL)
    LD (DE),A
    INC HL
    INC DE
    DJNZ READ_BYTE
    DEFB 0EDH,090H
    CALL RESET_BANKS
    EI
    LD DE,CASE_TEXT
    CALL PRINT
    LD A,(CASE_ID)
    CALL HEX
    LD HL,ACTUAL
    LD DE,EXPECTED
    LD B,12
COMPARE:
    LD A,(DE)
    CP (HL)
    JR NZ,FAILED
    INC HL
    INC DE
    DJNZ COMPARE
    LD HL,PASS_COUNT
    INC (HL)
    LD DE,PASS_TEXT
    CALL PRINT
    JR ADVANCE
FAILED:
    LD A,(HL)
    LD (BAD_GOT),A
    LD A,(DE)
    LD (BAD_WANT),A
    LD A,12
    SUB B
    LD (BAD_OFFSET),A
    LD HL,FAIL_COUNT
    INC (HL)
    LD DE,FAIL_TEXT
    CALL PRINT
    LD A,(BAD_OFFSET)
    CALL HEX
    LD DE,GOT_TEXT
    CALL PRINT
    LD A,(BAD_GOT)
    CALL HEX
    LD DE,WANT_TEXT
    CALL PRINT
    LD A,(BAD_WANT)
    CALL HEX
    LD DE,CRLF
    CALL PRINT
ADVANCE:
    LD A,(CASE_ID)
    INC A
    LD (CASE_ID),A
    CP 26
    JP C,NEXT_CASE
    DI
    LD A,(SAVED_MSP+2)
    DEFB 0EDH,024H
    LD HL,(SAVED_MSP)
    DEFB 0EDH,035H
    LD A,(SAVED_IBR)
    DEFB 0EDH,03AH
    LD A,(SAVED_I)
    LD I,A
    CALL RESET_BANKS
    EI
    LD DE,TOTAL
    CALL PRINT
    LD A,(PASS_COUNT)
    CALL HEX
    LD DE,TOTAL_FAIL
    CALL PRINT
    LD A,(FAIL_COUNT)
    CALL HEX
    LD DE,CRLF
    CALL PRINT
    LD C,0
    CALL 5
    RET
COPY_BYTES:
    LD A,(DE)
    LD (HL),A
    INC DE
    INC HL
    DEC C
    JR NZ,COPY_BYTES
    RET
RESET_BANKS:
    XOR A
    DEFB 0EDH,004H,0EDH,014H,0EDH,024H,0EDH,005H,0EDH,015H
    RET
PRINT:
    LD C,9
    CALL 5
    RET
HEX:
    PUSH AF
    RRCA
    RRCA
    RRCA
    RRCA
    CALL NIBBLE
    POP AF
NIBBLE:
    AND 0FH
    ADD A,'0'
    CP '9'+1
    JR C,EMIT
    ADD A,7
EMIT:
    LD E,A
    LD C,2
    CALL 5
    RET
CODE:
    DEFB 0EDH,085H,0
    LD (ACTUAL),A
    DEFB 0EDH,093H
    DEFW RETURN_M0
CODE_END:
VECTOR:
    DEFB 0EDH,0C3H,000H,081H,002H
HANDLER:
    LD A,05AH
    DEFB 0EDH,0C9H
OPERANDS: DEFB 0CFH,0FEH,0FFH,0
BANNER: DEFB "V16.1 RST.L / IBR / SYSCALL (DI)",13,10,"$"
CASE_TEXT: DEFB "Case $"
PASS_TEXT: DEFB ": PASS",13,10,"$"
FAIL_TEXT: DEFB ": FAIL offset=$"
GOT_TEXT: DEFB " got=$"
WANT_TEXT: DEFB " want=$"
TOTAL: DEFB "PASS=$"
TOTAL_FAIL: DEFB " FAIL=$"
CRLF: DEFB 13,10,"$"
EXPECTED: DEFB 05AH,0D7H,0,2,0,0E0H,2,2,080H,1,0,0
ACTUAL: DEFS 12
SAVED_I: DEFB 0
SAVED_IBR: DEFB 0
SAVED_MSP: DEFS 3
PASS_COUNT: DEFB 0
FAIL_COUNT: DEFB 0
CASE_ID: DEFB 0
BAD_OFFSET: DEFB 0
BAD_GOT: DEFB 0
BAD_WANT: DEFB 0
