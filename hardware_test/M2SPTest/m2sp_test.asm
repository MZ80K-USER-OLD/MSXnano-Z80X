CHECK_FAILED:
    LD A,(FAIL_COUNT)
    OR A
    JR NZ,FAIL_NOT_FIRST
    LD A,(CASE_ID)
    LD (FAIL_INDEX),A
    LD A,(LAST_GOT)
    LD (FAIL_GOT),A
    LD A,(LAST_WANT)
    LD (FAIL_WANT),A
FAIL_NOT_FIRST:
