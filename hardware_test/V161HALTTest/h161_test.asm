; Independent HALT / VDP IM2 IRQ comparison: M0, M1, M2.
    ORG 0100H
START:
    DI
    DEFB 0EDH,090H
    CALL RESET_BANKS
    LD (SAVED_SP),SP
    LD A,I
    LD (SAVED_I),A
    DEFB 0EDH,0EFH
    LD (SAVED_IBR),A
    DEFB 0EDH,036H
    LD (SAVED_MSP),HL
    DEFB 0EDH,02CH
    LD (SAVED_MSP+2),A
    LD A,(0F3E0H)
    LD (SAVED_R1),A
    LD DE,BANNER
    CALL PRINT
NEXT_CASE:
    LD DE,ARMED
    CALL PRINT
    LD A,(CASE_ID)
    CALL HEX
    LD DE,CRLF
    CALL PRINT
    DI
    CALL DISABLE_VDP
    LD HL,ACTUAL
    LD B,22
    XOR A
CLEAR:
    LD (HL),A
    INC HL
    DJNZ CLEAR
    LD A,0FEH
    LD (EXPECTED+10),A
    XOR A
    LD (EXPECTED+12),A
    LD (EXPECTED+15),A
    LD (EXPECTED+16),A
    LD (EXPECTED+19),A
    LD (EXPECTED+20),A
    DEFB 0EDH,091H
    LD HL,08000H
    LD DE,HALT_CODE
    LD C,HALT_CODE_END-HALT_CODE
    CALL COPY_BYTES
    LD HL,08190H
    LD DE,LEGACY_HANDLER
    LD C,LEGACY_HANDLER_END-LEGACY_HANDLER
    CALL COPY_BYTES
    LD HL,08181H
    LD DE,LEGACY_VECTOR
    LD C,3
    CALL COPY_BYTES
    LD HL,09000H
    CALL FILL_TABLE
    LD A,1
    DEFB 0EDH,024H
    LD HL,08000H
    LD DE,HALT_CODE
    LD C,HALT_CODE_END-HALT_CODE
    CALL COPY_BYTES
    LD A,2
    DEFB 0EDH,024H
    LD HL,08190H
    LD DE,LONG_HANDLER
    LD C,LONG_HANDLER_END-LONG_HANDLER
    CALL COPY_BYTES
    LD HL,08181H
    LD DE,LONG_VECTOR
    LD C,5
    CALL COPY_BYTES
    LD HL,09000H
    CALL FILL_TABLE
    LD HL,0D000H
    DEFB 0EDH,035H
    DEFB 0EDH,03AH
    DEFB 0EDH,090H
    CALL RESET_BANKS
    LD A,090H
    LD I,A
    IM 2
    LD A,(CASE_ID)
    ADD A,A
    ADD A,A
    ADD A,A
    LD B,A
    ADD A,A
    ADD A,A
    ADD A,B
    OUT (099H),A
    LD A,040H
    OUT (099H),A
    LD A,(CASE_ID)
    ADD A,'0'
    OUT (098H),A
    LD A,(SAVED_R1)
    OR 020H
    OUT (099H),A
    LD A,081H
    OUT (099H),A
    LD A,(CASE_ID)
    CP 2
    JR Z,ENTER_M2
    OR A
    JR NZ,ENTER_M1
    LD SP,0D000H
    JP 08000H
ENTER_M1:
    LD SP,0D000H
    DEFB 0EDH,094H
    DEFW 08000H
ENTER_M2:
    LD A,0FCH
    LD (EXPECTED+10),A
    LD A,2
    LD (EXPECTED+12),A
    LD (EXPECTED+16),A
    LD (EXPECTED+20),A
    LD A,1
    LD (EXPECTED+15),A
    LD (EXPECTED+19),A
    LD SP,0D000H
    DEFB 0EDH,09BH,000H,080H,001H
RETURN_M0:
    DI
    LD (ACTUAL+5),SP
    LD SP,(SAVED_SP)
    LD A,'M'
    OUT (098H),A
    DEFB 0EDH,036H
    LD (ACTUAL+7),HL
    DEFB 0EDH,02CH
    LD (ACTUAL+9),A
    CALL DISABLE_VDP
    IM 1
    LD A,(SAVED_I)
    LD I,A
    CALL RESET_BANKS
    LD A,(SAVED_R1)
    OUT (099H),A
    LD A,081H
    OUT (099H),A
    LD DE,CASE_TEXT
    CALL PRINT
    LD A,(CASE_ID)
    CALL HEX
    LD HL,ACTUAL
    LD DE,EXPECTED
    LD B,22
COMPARE:
    LD A,(DE)
    CP (HL)
    JR NZ,FAILED
    INC HL
    INC DE
    DJNZ COMPARE
    LD HL,PASS_COUNT
    INC (HL)
    LD DE,PASS_TEXT
    CALL PRINT
    JR ADVANCE
FAILED:
    LD A,(HL)
    LD (BAD_GOT),A
    LD A,(DE)
    LD (BAD_WANT),A
    LD A,22
    SUB B
    LD (BAD_OFFSET),A
    LD HL,FAIL_COUNT
    INC (HL)
    LD DE,FAIL_TEXT
    CALL PRINT
    LD A,(BAD_OFFSET)
    CALL HEX
    LD DE,GOT_TEXT
    CALL PRINT
    LD A,(BAD_GOT)
    CALL HEX
    LD DE,WANT_TEXT
    CALL PRINT
    LD A,(BAD_WANT)
    CALL HEX
    LD DE,CRLF
    CALL PRINT
ADVANCE:
    LD A,(CASE_ID)
    INC A
    LD (CASE_ID),A
    CP 3
    JP C,NEXT_CASE
    LD A,(SAVED_MSP+2)
    DEFB 0EDH,024H
    LD HL,(SAVED_MSP)
    DEFB 0EDH,035H
    LD A,(SAVED_IBR)
    DEFB 0EDH,03AH
    CALL RESET_BANKS
    LD DE,TOTAL
    CALL PRINT
    LD A,(PASS_COUNT)
    CALL HEX
    LD DE,TOTAL_FAIL
    CALL PRINT
    LD A,(FAIL_COUNT)
    CALL HEX
    LD DE,CRLF
    CALL PRINT
    EI
    LD C,0
    CALL 5
    RET
DISABLE_VDP:
    XOR A
    OUT (099H),A
    LD A,08FH
    OUT (099H),A
    IN A,(099H)
    LD A,(SAVED_R1)
    AND 0DFH
    OUT (099H),A
    LD A,081H
    OUT (099H),A
    IN A,(099H)
    RET
COPY_BYTES:
    LD A,(DE)
    LD (HL),A
    INC DE
    INC HL
    DEC C
    JR NZ,COPY_BYTES
    RET
FILL_TABLE:
    LD B,0
FILL_LOOP:
    LD (HL),081H
    INC HL
    DJNZ FILL_LOOP
    LD (HL),081H
    RET
RESET_BANKS:
    XOR A
    DEFB 0EDH,004H,0EDH,014H,0EDH,024H,0EDH,005H,0EDH,015H
    RET
PRINT:
    LD C,9
    CALL 5
    DI
    RET
HEX:
    PUSH AF
    RRCA
    RRCA
    RRCA
    RRCA
    CALL NIBBLE
    POP AF
NIBBLE:
    AND 0FH
    ADD A,'0'
    CP '9'+1
    JR C,EMIT
    ADD A,7
EMIT:
    LD E,A
    LD C,2
    CALL 5
    DI
    RET
HALT_CODE:
    LD A,'A'
    OUT (098H),A
    LD A,'H'
    OUT (098H),A
    EI
    HALT
AFTER_FIRST:
    LD A,'R'
    OUT (098H),A
    LD A,1
    LD (ACTUAL+3),A
    LD A,I
    PUSH AF
    POP HL
    LD A,L
    AND 4
    LD (ACTUAL+1),A
    IN A,(099H)
    LD A,'H'
    OUT (098H),A
    EI
    HALT
AFTER_SECOND:
    LD A,'R'
    OUT (098H),A
    LD A,1
    LD (ACTUAL+4),A
    LD A,I
    PUSH AF
    POP HL
    LD A,L
    AND 4
    LD (ACTUAL+2),A
    DEFB 0EDH,093H
    DEFW RETURN_M0
HALT_CODE_END:
LEGACY_VECTOR:
    JP 08190H
LONG_VECTOR:
    DEFB 0EDH,0C3H,090H,081H,002H
LEGACY_HANDLER:
    EX AF,AF'
    LD A,'V'
    OUT (098H),A
    EXX
    LD HL,0
    ADD HL,SP
    LD (ACTUAL+10),HL
    LD DE,ACTUAL+13
    LD A,(ACTUAL)
    OR A
    JR Z,LEGACY_COPY
    LD DE,ACTUAL+17
LEGACY_COPY:
    LD A,(HL)
    LD (DE),A
    INC HL
    INC DE
    LD A,(HL)
    LD (DE),A
    LD A,05AH
    LD (ACTUAL+21),A
    LD A,'S'
    OUT (098H),A
    IN A,(099H)
    LD A,(ACTUAL)
    INC A
    LD (ACTUAL),A
    LD A,'K'
    OUT (098H),A
    EXX
    EX AF,AF'
    RETI
LEGACY_HANDLER_END:
LONG_HANDLER:
    EX AF,AF'
    LD A,05AH
    LD (ACTUAL+21),A
    LD A,'V'
    OUT (098H),A
    EXX
    DEFB 0EDH,036H
    LD (ACTUAL+10),HL
    DEFB 0EDH,02CH
    LD (ACTUAL+12),A
    LD DE,ACTUAL+13
    LD A,(ACTUAL)
    OR A
    JR Z,LONG_COPY_START
    LD DE,ACTUAL+17
LONG_COPY_START:
    LD B,4
LONG_COPY:
    LD A,(HL)
    LD (DE),A
    INC HL
    INC DE
    DJNZ LONG_COPY
    XOR A
    DEFB 0EDH,024H
    LD A,'S'
    OUT (098H),A
    IN A,(099H)
    LD A,(ACTUAL)
    INC A
    LD (ACTUAL),A
    LD A,'K'
    OUT (098H),A
    EXX
    EX AF,AF'
    DEFB 0EDH,0F3H
LONG_HANDLER_END:
BANNER: DEFB "V16.1 HALT / VDP IM2: M0 M1 M2",13,10,"$"
ARMED: DEFB "HALT arming M$"
CASE_TEXT: DEFB "HALT M$"
PASS_TEXT: DEFB ": PASS",13,10,"$"
FAIL_TEXT: DEFB ": FAIL offset=$"
GOT_TEXT: DEFB " got=$"
WANT_TEXT: DEFB " want=$"
TOTAL: DEFB "PASS=$"
TOTAL_FAIL: DEFB " FAIL=$"
CRLF: DEFB 13,10,"$"
EXPECTED:
    DEFB 2,0,0,1,1
    DEFW 0D000H,0D000H
    DEFB 2,0FEH,0CFH,0
    DEFW 08000H+AFTER_FIRST-HALT_CODE
    DEFB 0,0
    DEFW 08000H+AFTER_SECOND-HALT_CODE
    DEFB 0,0,05AH
ACTUAL: DEFS 22
SAVED_SP: DEFW 0
SAVED_I: DEFB 0
SAVED_IBR: DEFB 0
SAVED_MSP: DEFS 3
SAVED_R1: DEFB 0
CASE_ID: DEFB 0
PASS_COUNT: DEFB 0
FAIL_COUNT: DEFB 0
BAD_OFFSET: DEFB 0
BAD_GOT: DEFB 0
BAD_WANT: DEFB 0
