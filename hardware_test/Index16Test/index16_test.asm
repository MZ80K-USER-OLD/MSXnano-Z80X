; V15 indexed16 hardware test. Only banks 00/01/02 are accessed.
; Instruction code migration and M2 interrupt changes are not included.
IFDEF INDEX24
STORE_BIT EQU 5
BASE_BYTES EQU 19
ELSE
STORE_BIT EQU 3
BASE_BYTES EQU 18
ENDIF
IFDEF M2TEST
STATE_BYTES EQU BASE_BYTES+5
ELSE
STATE_BYTES EQU BASE_BYTES
ENDIF
    org 0100H
START:
    DI
    DEFB 0EDH,090H
    CALL RESET_BANKS
    EI
    XOR A
    LD (PASS_COUNT),A
    LD (FAIL_COUNT),A
    LD (CASE_ID),A
    LD DE,BANNER
    CALL PRINT
NEXT_CASE:
IFDEF M2TEST
    LD (EXPECTED+BASE_BYTES+3),SP
ENDIF
    ; Patch the instruction while still in M0.
    LD A,(CASE_ID)
    LD L,A
    LD H,0
    LD DE,OPCODES
    ADD HL,DE
    LD A,(HL)
    LD (INSTRUCTION+1),A
    LD A,(CASE_ID)
    AND 1
    LD A,0DDH
    JR Z,SET_PREFIX
    LD A,0FDH
SET_PREFIX:
    LD (INSTRUCTION),A
    LD A,(CASE_ID)
    CP 12
    LD A,0
    LD IX,0FFFFH
    LD IY,0FFFFH
    LD B,1
    JR C,SET_DISPLACEMENT
    LD A,0FFH
    LD IX,0
    LD IY,0
    LD B,2
SET_DISPLACEMENT:
    LD (INSTRUCTION+2),A
    LD A,B
    DEFB 0EDH,005H
    DEFB 0EDH,015H
    LD (EXPECTED+6),IX
    LD (EXPECTED+8),IY
    LD (EXPECTED+13),A
    LD (EXPECTED+14),A
    LD HL,EXPECTED
    LD B,3
EXPECT_PAIRS:
    LD (HL),034H
    INC HL
    LD (HL),012H
    INC HL
    DJNZ EXPECT_PAIRS
IFDEF INDEX24
    LD A,067H
    LD (EXPECTED+10),A
    LD (EXPECTED+11),A
    LD (EXPECTED+12),A
    LD A,0A5H
    LD (EXPECTED+18),A
ENDIF
    LD A,(INSTRUCTION+1)
    BIT STORE_BIT,A
    JR Z,EXPECT_LOAD
    LD HL,EXPECTED
    LD B,3
EXPECT_STORES:
    LD (HL),0EFH
    INC HL
    LD (HL),0BEH
    INC HL
    DJNZ EXPECT_STORES
IFDEF INDEX24
    LD A,067H
    LD (EXPECTED+18),A
ENDIF
    JR PREPARE
EXPECT_LOAD:
IFDEF INDEX24
    SUB 8
    RRCA
    RRCA
    AND 6
ELSE
    AND 030H
    RRCA
    RRCA
    RRCA
ENDIF
    LD E,A
    LD D,0
    LD HL,EXPECTED
    ADD HL,DE
    LD (HL),0EFH
    INC HL
    LD (HL),0BEH
IFDEF INDEX24
    LD HL,EXPECTED+10
    SRL E
    ADD HL,DE
    LD (HL),0A5H
ENDIF
PREPARE:
    DI
IFDEF M2TEST
    XOR A
    DEFB 0EDH,024H
    LD HL,M2_STACK_END
    DEFB 0EDH,035H
    DEFB 0EDH,092H
ELSE
    DEFB 0EDH,091H
ENDIF
    ; Alternate initialization with the opposite value before the operation.
    LD BC,0FFFFH
    LD A,1
    DEFB 0EDH,004H
    LD A,(INSTRUCTION+1)
    BIT STORE_BIT,A
    LD A,0EFH
    JR Z,PREP_LOW
    LD A,034H
PREP_LOW:
    LD (BC),A
    LD BC,0
    LD A,2
    DEFB 0EDH,004H
    LD A,(INSTRUCTION+1)
    BIT STORE_BIT,A
    LD A,0BEH
    JR Z,PREP_HIGH
    LD A,012H
PREP_HIGH:
    LD (BC),A
IFDEF INDEX24
    INC BC
    LD A,(INSTRUCTION+1)
    BIT STORE_BIT,A
    LD A,0A5H
    JR Z,PREP_BANK
    LD A,098H
PREP_BANK:
    LD (BC),A
ENDIF
    LD A,067H
    DEFB 0EDH,004H
    DEFB 0EDH,014H
    DEFB 0EDH,024H
    LD BC,00D7H
    PUSH BC
    POP AF
    LD BC,1234H
    LD DE,1234H
    LD HL,1234H
    ; LD does not modify flags: select source values without changing F.
    JP SELECT_VALUES
RUN:
INSTRUCTION:
    DEFB 0DDH,007H,000H
    LD (ACTUAL),BC
    LD (ACTUAL+2),DE
    LD (ACTUAL+4),HL
    LD (ACTUAL+6),IX
    LD (ACTUAL+8),IY
    PUSH AF
    POP BC
    LD A,C
    LD (ACTUAL+15),A
    DEFB 0EDH,00CH
    LD (ACTUAL+10),A
    DEFB 0EDH,01CH
    LD (ACTUAL+11),A
    DEFB 0EDH,02CH
    LD (ACTUAL+12),A
    DEFB 0EDH,00DH
    LD (ACTUAL+13),A
    DEFB 0EDH,01DH
    LD (ACTUAL+14),A
    LD BC,0FFFFH
    LD A,1
    DEFB 0EDH,004H
    LD A,(BC)
    LD (ACTUAL+16),A
    LD BC,0
    LD A,2
    DEFB 0EDH,004H
    LD A,(BC)
    LD (ACTUAL+17),A
IFDEF INDEX24
    INC BC
    LD A,(BC)
    LD (ACTUAL+18),A
ENDIF
IFDEF M2TEST
    DEFB 0EDH,036H
    LD (ACTUAL+BASE_BYTES),HL
    DEFB 0EDH,02CH
    LD (ACTUAL+BASE_BYTES+2),A
ENDIF
    DEFB 0EDH,090H
    CALL RESET_BANKS
IFDEF M2TEST
    LD HL,0
    ADD HL,SP
    LD (ACTUAL+BASE_BYTES+3),HL
ENDIF
    EI
    LD DE,CASE_TEXT
    CALL PRINT
    LD A,(CASE_ID)
    CALL HEX
    LD HL,ACTUAL
    LD DE,EXPECTED
    LD B,STATE_BYTES
COMPARE:
    LD A,(DE)
    CP (HL)
    JR NZ,FAILED
    INC HL
    INC DE
    DJNZ COMPARE
    LD HL,PASS_COUNT
    INC (HL)
    LD DE,PASS_TEXT
    CALL PRINT
    JR ADVANCE
FAILED:
    LD A,(HL)
    LD (BAD_GOT),A
    LD A,(DE)
    LD (BAD_WANT),A
    LD A,STATE_BYTES
    SUB B
    LD (BAD_OFFSET),A
    LD HL,FAIL_COUNT
    INC (HL)
    LD DE,FAIL_TEXT
    CALL PRINT
    LD A,(BAD_OFFSET)
    CALL HEX
    LD DE,GOT_TEXT
    CALL PRINT
    LD A,(BAD_GOT)
    CALL HEX
    LD DE,WANT_TEXT
    CALL PRINT
    LD A,(BAD_WANT)
    CALL HEX
    LD DE,CRLF
    CALL PRINT
ADVANCE:
    LD A,(CASE_ID)
    INC A
    LD (CASE_ID),A
    CP 24
    JP C,NEXT_CASE
    LD DE,TOTAL
    CALL PRINT
    LD A,(PASS_COUNT)
    CALL HEX
    LD DE,TOTAL_FAIL
    CALL PRINT
    LD A,(FAIL_COUNT)
    CALL HEX
    LD DE,CRLF
    CALL PRINT
    LD C,0
    CALL 5
    RET
SELECT_VALUES:
    ; Preserve the known flag pattern across the load/store selection.
    PUSH AF
    LD A,(INSTRUCTION+1)
    BIT STORE_BIT,A
    JR Z,VALUES_READY
    LD BC,0BEEFH
    LD DE,0BEEFH
    LD HL,0BEEFH
VALUES_READY:
    POP AF
    JP RUN
RESET_BANKS:
    XOR A
    DEFB 0EDH,004H,0EDH,014H,0EDH,024H,0EDH,005H,0EDH,015H
    RET
PRINT:
    LD C,9
    CALL 5
    RET
HEX:
    PUSH AF
    RRCA
    RRCA
    RRCA
    RRCA
    CALL NIBBLE
    POP AF
NIBBLE:
    AND 0FH
    ADD A,'0'
    CP '9'+1
    JR C,EMIT
    ADD A,7
EMIT:
    LD E,A
    LD C,2
    CALL 5
    RET
OPCODES:
IFDEF INDEX24
    DEFB 08H,08H,10H,10H,18H,18H,20H,20H,28H,28H,30H,30H
    DEFB 08H,08H,10H,10H,18H,18H,20H,20H,28H,28H,30H,30H
BANNER: DEFB "V15 INDEX24 "
ELSE
    DEFB 07H,07H,17H,17H,27H,27H,0FH,0FH,1FH,1FH,2FH,2FH
    DEFB 07H,07H,17H,17H,27H,27H,0FH,0FH,1FH,1FH,2FH,2FH
BANNER: DEFB "V15 INDEX16 "
ENDIF
IFDEF M2TEST
    DEFB "M2"
ELSE
    DEFB "M1"
ENDIF
    DEFB " / banks 00,01,02",13,10,"$"
CASE_TEXT: DEFB "Case $"
PASS_TEXT: DEFB ": PASS",13,10,"$"
FAIL_TEXT: DEFB ": FAIL offset=$"
GOT_TEXT: DEFB " got=$"
WANT_TEXT: DEFB " want=$"
TOTAL: DEFB "PASS=$"
TOTAL_FAIL: DEFB " FAIL=$"
CRLF: DEFB 13,10,"$"
EXPECTED:
    DEFB 034H,012H,034H,012H,034H,012H
    DEFS 4
    DEFB 067H,067H,067H,1,1,0D7H,0EFH,0BEH
IFDEF INDEX24
    DEFB 0A5H
ENDIF
IFDEF M2TEST
    DEFW M2_STACK_END
    DEFB 0
    DEFW 0
ENDIF
ACTUAL: DEFS STATE_BYTES
PASS_COUNT: DEFB 0
FAIL_COUNT: DEFB 0
CASE_ID: DEFB 0
BAD_OFFSET: DEFB 0
BAD_GOT: DEFB 0
BAD_WANT: DEFB 0
IFDEF M2TEST
M2_STACK: DEFS 32
M2_STACK_END:
ENDIF
